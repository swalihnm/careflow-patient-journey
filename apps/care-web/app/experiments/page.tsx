"use client";

import { marked } from "marked";
import { useApi } from "@/lib/use-api";
import { Loading, ErrorBanner, Forbidden } from "@/components/StatusStates";
import type { ExperimentReport } from "@/lib/api";

const EXPERIMENT_ID = "reminder-ab-v1";

export default function ExperimentsPage() {
  const { data, loading, error, forbidden } = useApi<ExperimentReport>(
    `/v1/experiments/${EXPERIMENT_ID}/report`
  );

  return (
    <div>
      <h1 className="page-title">Experiments</h1>
      <p className="page-subtitle">
        Reminder A/B report: power analysis, effect size and confidence interval. Outcomes are simulated from
        real patients scored by the real no-show model -- see the report&apos;s own caveats section.
      </p>

      {forbidden && <Forbidden requiredRoles="admin, clinician" />}
      {error && <ErrorBanner message={error} />}
      {loading && <Loading />}

      {!loading && data && (
        <div className="card">
          <h2>{data.experiment_id}</h2>
          {/* The report is generated by ml/experiment/report.py, a trusted
              source in this repo, not user input -- safe to render as HTML. */}
          <div
            className="markdown-report"
            dangerouslySetInnerHTML={{ __html: marked.parse(data.report_markdown, { async: false }) }}
          />
        </div>
      )}
    </div>
  );
}
