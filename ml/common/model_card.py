"""Renders a model card markdown file from a metrics dict (SPEC 6.2: "intended
use, data provenance and dates, metrics, subgroup results, known limitations,
not for diagnosis")."""

import math
from datetime import UTC, datetime
from pathlib import Path
from typing import Any


def render_model_card(
    *,
    title: str,
    intended_use: str,
    data_provenance: str,
    baseline_name: str,
    baseline_metrics: dict[str, Any],
    main_metrics: dict[str, Any],
    subgroup_reports: dict[str, Any],
    limitations: list[str],
    model_version: str,
    calibration_plot_filename: str | None = None,
) -> str:
    lines = [
        f"# Model card: {title}",
        "",
        f"Generated {datetime.now(UTC).date().isoformat()} · model version `{model_version}`",
        "",
        (
            "> Decision support for clinicians only. Not for diagnosis. Patients never "
            "see this score (SPEC clinical safety rule 4)."
        ),
        "",
        "## Intended use",
        "",
        intended_use,
        "",
        "## Data provenance",
        "",
        data_provenance,
        "",
        "## Metrics",
        "",
        f"| Metric | {baseline_name} (baseline) | Main model |",
        "| --- | --- | --- |",
    ]
    for key, main_val in main_metrics.items():
        base_val = baseline_metrics.get(key, "—")
        lines.append(f"| {key} | {base_val} | {main_val} |")

    if calibration_plot_filename:
        lines += ["", f"![Calibration]({calibration_plot_filename})"]

    lines += ["", "## Subgroup fairness", ""]
    for feature_name, report in subgroup_reports.items():
        metric_names = list(report.metric_gaps.keys())
        gap_line = "  \n".join(f"Max {m} gap across subgroups: **{g:.4f}**" for m, g in report.metric_gaps.items())
        lines += [
            f"### By `{feature_name}`",
            "",
            gap_line,
            "",
            "| Group | n | " + " | ".join(metric_names) + " |",
            "| --- | --- | " + " | ".join("---" for _ in metric_names) + " |",
        ]
        for group, vals in report.by_group.items():
            cells = []
            for m in metric_names:
                v = vals[m]
                cells.append(f"{v:.4f}" if not math.isnan(v) else "n/a (single class)")
            lines.append(f"| {group} | {int(vals['n'])} | " + " | ".join(cells) + " |")
        lines.append("")

    lines += [
        "",
        "## Known limitations",
        "",
    ]
    for item in limitations:
        lines.append(f"- {item}")

    generated_at = datetime.now(UTC).isoformat(timespec="seconds")
    lines += [
        "",
        f"---\n_Generated by `ml/{title.lower().replace(' ', '_')}` training script, {generated_at}._",
    ]
    return "\n".join(lines)


def write_model_card(path: Path, **kwargs) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_model_card(**kwargs), encoding="utf-8")
